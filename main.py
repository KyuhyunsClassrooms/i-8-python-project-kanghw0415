# 아래 예시는 "활동 추천 프로그램"입니다.
# 자신의 주제에 맞게 data를 만드세요.
#
# 현재 열의 의미:
# 0번 열: 활동 이름
# 1번 열: 필요한 시간(분)
# 2번 열: 추천 기분
# 3번 열: 활동 유형
# ------------------------------------------------------------
activities = [
    ["맑음", 28, 40, "반팔, 반바지"],
    ["맑음", 23, 27, "반팔, 얇은 셔츠"],
    ["흐림", 17, 22, "긴팔, 가디건"],
    ["비", 10, 16, "자켓, 우산"],
    ["눈", -10, 9, "패딩, 목도리"]
]
# ------------------------------------------------------------
# 2. 함수 정의
# ------------------------------------------------------------

def show_intro():
    print("=" * 40)
    print("날씨와 온도에 따른 옷차림 추천 프로그램")
    print("=" * 40)



def get_user_input():
    weather = input("오늘 날씨를 입력하세요 (맑음, 흐림, 비, 눈): ")
    temperature = int(input("현재 온도를 입력하세요(℃): "))
    return weather, temperature


def find_clothes(data, weather, temperature):
    result = []

    for row in data:
        weather_type = row[0]
        min_temp = row[1]
        max_temp = row[2]
        clothes = row[3]

        if weather == weather_type and min_temp <= temperature <= max_temp:
            result.append(clothes)

    return result

def print_result(result):
    print("\n[추천 결과]")

    if len(result) == 0:
        print("조건에 맞는 옷차림 정보가 없습니다.")
    else:
        for clothes in result:
            print("추천 옷차림:", clothes)

def main():
    show_intro()
    weather, temperature = get_user_input()
    result = find_clothes(activities, weather, temperature)
    print_result(result)
# ------------------------------------------------------------
# 3. 프로그램 실행
# ------------------------------------------------------------
main()
